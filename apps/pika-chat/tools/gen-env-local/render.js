// renderEnvFile returns the text of a .env.local file built from task definition variables.
export class EnvValueError extends Error {}

// Single quotes are the only form dotenv carries verbatim: unquoted truncates at a '#', and
// double-quoted expands \n while leaving \\ alone, so it cannot round-trip a backslash. There is
// no escape for a single quote inside single quotes, hence the throw rather than a mangled value.
export function quote(name, value) {
    const v = value ?? '';
    if (v.includes("'")) {
        throw new EnvValueError(`${name} contains a single quote, which .env cannot represent. Set it by hand.`);
    }
    return `'${v}'`;
}

export function renderEnvFile({ taskDefName, stage, generatedAt, webappUrl, vars, strandsPort, strandsUrl }) {
    const sorted = vars.filter((e) => e.name !== 'WEBAPP_URL').sort((a, b) => a.name.localeCompare(b.name));

    return (
        [
            `# Generated by gen-env-local.mjs from ${taskDefName}`,
            `# Stage: ${stage}   Generated: ${generatedAt}`,
            '# Gitignored - regenerate rather than copying between worktrees.',
            '',
            `WEBAPP_URL=${quote('WEBAPP_URL', webappUrl)}`,
            ...sorted.map((e) => `${e.name}=${quote(e.name, e.value)}`),
            '',
            '# Skip the login round-trip. Gated on isLocal; inert when deployed.',
            'PIKA_LOCAL_MOCK_AUTH=true',
            '',
            '# Local Strands converse. dev:nosudo starts it and exports this; the line is here so a bare',
            '# `vite dev` does not fall back to the deprecated in-process TS converse.',
            '# Must be a loopback or Lambda function URL.',
            `LOCAL_CONVERSE_FUNCTION_URL=http://127.0.0.1:${strandsPort}`,
            ...(strandsUrl
                ? ['# Deployed Strands lambda, to test against TEST instead of running it locally:', `# LOCAL_CONVERSE_FUNCTION_URL=${strandsUrl}`]
                : []),
            '',
            '# Identity overrides',
            '# PIKA_LOCAL_MOCK_USER_ID=',
            '# PIKA_LOCAL_MOCK_ACCOUNT_ID=',
            '# PIKA_LOCAL_MOCK_ACCOUNT_TYPE='
        ].join('\n') + '\n'
    );
}
